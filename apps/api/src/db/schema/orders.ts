import { boolean, integer, jsonb, pgTable, text, timestamp, uuid, bigint } from 'drizzle-orm/pg-core';

export const orders = pgTable('orders', {
  id: uuid('id').primaryKey().defaultRandom(),
  tenantId: uuid('tenant_id').notNull(),
  outletId: uuid('outlet_id').notNull(),
  tableId: uuid('table_id'),
  billingGroupId: uuid('billing_group_id'),
  billingGroupPrimary: boolean('billing_group_primary').notNull().default(false),
  assignedWaiterId: uuid('assigned_waiter_id'),
  orderType: text('order_type').notNull(),
  status: text('status').notNull().default('OPEN'),
  notes: text('notes').notNull().default(''),
  createdBy: uuid('created_by').notNull(),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
  deletedAt: timestamp('deleted_at', { withTimezone: true }),
  version: integer('version').notNull().default(1),
});

export const kotTickets = pgTable('kot_tickets', {
  id: uuid('id').primaryKey().defaultRandom(),
  tenantId: uuid('tenant_id').notNull(),
  outletId: uuid('outlet_id').notNull(),
  orderId: uuid('order_id').notNull(),
  ticketNumber: bigint('ticket_number', { mode: 'bigint' }).generatedAlwaysAsIdentity(),
  status: text('status').notNull().default('QUEUED'),
  createdBy: uuid('created_by').notNull(),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
  deletedAt: timestamp('deleted_at', { withTimezone: true }),
  version: integer('version').notNull().default(1),
});

export const orderItems = pgTable('order_items', {
  id: uuid('id').primaryKey().defaultRandom(),
  tenantId: uuid('tenant_id').notNull(),
  outletId: uuid('outlet_id').notNull(),
  orderId: uuid('order_id').notNull(),
  kotTicketId: uuid('kot_ticket_id'),
  categoryId: uuid('category_id').notNull(),
  menuItemId: uuid('menu_item_id').notNull(),
  variantId: uuid('variant_id').notNull(),
  itemName: text('item_name').notNull(),
  variantName: text('variant_name').notNull(),
  quantity: integer('quantity').notNull(),
  unitPrice: bigint('unit_price', { mode: 'bigint' }).notNull(),
  taxCode: text('tax_code').notNull(),
  cgstRate: integer('cgst_rate').notNull(),
  sgstRate: integer('sgst_rate').notNull(),
  igstRate: integer('igst_rate').notNull(),
  addOns: jsonb('add_ons').$type<Array<{ id: string; name: string; price: string }>>().notNull().default([]),
  notes: text('notes').notNull().default(''),
  status: text('status').notNull().default('PENDING'),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
  deletedAt: timestamp('deleted_at', { withTimezone: true }),
  version: integer('version').notNull().default(1),
});
