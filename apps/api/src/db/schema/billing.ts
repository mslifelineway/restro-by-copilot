import { bigint, integer, jsonb, pgTable, text, timestamp, uuid } from 'drizzle-orm/pg-core';

export const invoices = pgTable('invoices', {
  id: uuid('id').primaryKey().defaultRandom(),
  tenantId: uuid('tenant_id').notNull(),
  outletId: uuid('outlet_id').notNull(),
  orderId: uuid('order_id').notNull(),
  invoiceNumber: text('invoice_number').notNull(),
  financialYear: text('financial_year').notNull(),
  series: text('series').notNull(),
  tenantName: text('tenant_name').notNull(),
  outletName: text('outlet_name').notNull(),
  outletGstin: text('outlet_gstin'),
  taxableAmount: bigint('taxable_amount', { mode: 'bigint' }).notNull(),
  cgstAmount: bigint('cgst_amount', { mode: 'bigint' }).notNull(),
  sgstAmount: bigint('sgst_amount', { mode: 'bigint' }).notNull(),
  igstAmount: bigint('igst_amount', { mode: 'bigint' }).notNull(),
  totalTax: bigint('total_tax', { mode: 'bigint' }).notNull(),
  discountType: text('discount_type'),
  discountValue: bigint('discount_value', { mode: 'bigint' }).notNull().default(0n),
  discountAmount: bigint('discount_amount', { mode: 'bigint' }).notNull().default(0n),
  serviceChargeAmount: bigint('service_charge_amount', { mode: 'bigint' }).notNull().default(0n),
  serviceChargeTaxableAmount: bigint('service_charge_taxable_amount', { mode: 'bigint' }).notNull().default(0n),
  serviceChargeTax: bigint('service_charge_tax', { mode: 'bigint' }).notNull().default(0n),
  serviceChargeTaxCode: text('service_charge_tax_code'),
  serviceChargeCgstRate: integer('service_charge_cgst_rate').notNull().default(0),
  serviceChargeSgstRate: integer('service_charge_sgst_rate').notNull().default(0),
  serviceChargeIgstRate: integer('service_charge_igst_rate').notNull().default(0),
  serviceChargeCgstAmount: bigint('service_charge_cgst_amount', { mode: 'bigint' }).notNull().default(0n),
  serviceChargeSgstAmount: bigint('service_charge_sgst_amount', { mode: 'bigint' }).notNull().default(0n),
  serviceChargeIgstAmount: bigint('service_charge_igst_amount', { mode: 'bigint' }).notNull().default(0n),
  tipAmount: bigint('tip_amount', { mode: 'bigint' }).notNull().default(0n),
  roundOffAmount: bigint('round_off_amount', { mode: 'bigint' }).notNull().default(0n),
  totalAmount: bigint('total_amount', { mode: 'bigint' }).notNull(),
  finalizedBy: uuid('finalized_by').notNull(),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
  deletedAt: timestamp('deleted_at', { withTimezone: true }),
  version: integer('version').notNull().default(1),
});

export const invoiceLines = pgTable('invoice_lines', {
  id: uuid('id').primaryKey().defaultRandom(),
  tenantId: uuid('tenant_id').notNull(),
  outletId: uuid('outlet_id').notNull(),
  invoiceId: uuid('invoice_id').notNull(),
  orderItemId: uuid('order_item_id').notNull(),
  itemName: text('item_name').notNull(),
  variantName: text('variant_name').notNull(),
  quantity: integer('quantity').notNull(),
  unitPrice: bigint('unit_price', { mode: 'bigint' }).notNull(),
  addOns: jsonb('add_ons').$type<Array<{ id: string; name: string; price: string }>>().notNull(),
  taxCode: text('tax_code').notNull(),
  cgstRate: integer('cgst_rate').notNull(),
  sgstRate: integer('sgst_rate').notNull(),
  igstRate: integer('igst_rate').notNull(),
  discountAmount: bigint('discount_amount', { mode: 'bigint' }).notNull().default(0n),
  taxableAmount: bigint('taxable_amount', { mode: 'bigint' }).notNull(),
  cgstAmount: bigint('cgst_amount', { mode: 'bigint' }).notNull(),
  sgstAmount: bigint('sgst_amount', { mode: 'bigint' }).notNull(),
  igstAmount: bigint('igst_amount', { mode: 'bigint' }).notNull(),
  totalTax: bigint('total_tax', { mode: 'bigint' }).notNull(),
  totalAmount: bigint('total_amount', { mode: 'bigint' }).notNull(),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
});

